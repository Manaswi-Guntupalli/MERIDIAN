// Each record carries two views of every field:
//
//   `print` — exactly what gets typed onto the paper ("18/08/2011")
//   `truth` — what Lumen is expected to produce ("2011-08-18")
//
// They differ wherever normalisation is supposed to do work, and that gap is
// the point: the benchmark compares against `truth`, so it grades the whole
// pipeline (read → repair → normalise), not just the OCR. Grading against the
// printed string would let a system that never normalises anything score 100%.
//
// The data is deliberately varied — different date shapes, currency formats,
// blood groups, an ambiguous date or two — so the benchmark exercises the
// branches rather than one happy path nine times.

